/**
 * 内置曲库：全部为公有领域旋律的简化编配（一句一行，便于逐句显示歌词）。
 * 音符用 MIDI 表示（C4=60），d 为拍数，ly 为该音对应的歌词字；
 * ly 为空字符串表示上一个字的延音（转音），m=0 表示休止。
 */

export interface SongNote {
  m: number; // MIDI 音高，0 = 休止
  d: number; // 时值（拍）
  ly?: string; // 歌词字
}

export interface Song {
  id: string;
  name: string;
  emoji: string;
  level: string; // 难度标签
  bpm: number;
  lines: SongNote[][]; // 按句分组
}

// 简谱度数 → 相对 C 的半音数（1=do ... 7=ti）
const DEG = [0, 0, 2, 4, 5, 7, 9, 11];

/** n(度数, 拍数, 歌词, 八度偏移)；度数 0 为休止 */
function n(deg: number, d: number, ly?: string, oct = 0): SongNote {
  return { m: deg === 0 ? 0 : 60 + DEG[deg] + oct * 12, d, ly };
}

