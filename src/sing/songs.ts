/** 展平为音符序列（保留句边界索引，用于打分与歌词显示） */
export function flattenSong(song: Song): { notes: SongNote[]; lineStart: number[] } {
  const notes: SongNote[] = [];
  const lineStart: number[] = [];
  for (const line of song.lines) {
    lineStart.push(notes.length);
    for (const nt of line) notes.push(nt);
  }
  return { notes, lineStart };
}

/** 歌曲的音域（不含休止） */
export function songRange(song: Song): { lo: number; hi: number } {
  let lo = 127;
  let hi = 0;
  for (const line of song.lines)
    for (const nt of line)
      if (nt.m > 0) {
        lo = Math.min(lo, nt.m);
        hi = Math.max(hi, nt.m);
      }
  return { lo, hi };
}
