/**
 * 布局体系的"种子谱"：每一套前面几个回合按定式写，每一手配一句人写的说明。
 * tools/build-openings.ts 拿它让皮卡鱼逐手核对，再往后深算延伸到 15 回合左右，
 * 并在双方选择最多的地方补上变化，生成 openinglib.json（界面用的是那份）。
 *
 * 用户原话："多走几步，不要只走两三步就草草了事……认真按正常谱路去推演。"
 * 所以种子只写到这一路"成型"的那几手（谱上公认的走法），之后交给引擎——
 * 引擎深算出来的才是"认真推演"，人凭记忆往下写十几手，十有八九会写错。
 */

export interface SeedMove {
  t: string;
  why: string;
  /** 这一路的特征着：引擎不认可也照写（江湖攻法本身就有毛病，正好拿来教怎么破） */
  allow?: boolean;
}

export interface OpeningSpec {
  id: string;
  /** 布局名 */
  name: string;
  /** 归在哪个体系下（列表分组用） */
  system: string;
  /** 这一套是谁的布局（学的时候默认执这一方） */
  side: 'red' | 'black';
  tag: string;
  /** 核心思路 */
  idea: string;
  /** 对方怎么破（或者：这一方怎么破对方的攻法） */
  breaks: string;
  seed: SeedMove[];
  /** 主线一共走多少手（双方合计），种子之后由引擎补齐 */
  plies: number;
  /** 人写的变化：在第 at 手（从 0 数）换一手走，再往后延伸 */
  variations?: { name: string; at: number; seed: SeedMove[]; plies: number }[];
  traps: string[];
}

