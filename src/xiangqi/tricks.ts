/**
 * 邪门布局（江湖套路）的破解。
 *
 * 只收江湖上真有名号、真有人走的套路：弃马十三着、铁滑车、双铁滑车、敢死炮、急进中兵、叠炮、
 * 瞎眼狗、龟背炮……原来收的"开局炮打中卒""炮打底马"那一类不算邪门布局——
 * 用户原话："哪有炮打中卒这种？……直接炮打中兵送在人家马口上，这种肯定不叫邪门布局。"
 *
 * 这些套路的精髓是"宁失一子，不失一先"：送一个子（或者一个兵、一条线），换几步先手。
 * 所以每一条除了怎么破，还要把账算给你看（essence + 界面上的账本）：
 *   他送了什么、你吃到手那一刻他少多少子力、引擎却判他落后多少（甚至领先）——
 *   子力差和局面分之间那一截，就是他用子换来的"先"值多少。
 *
 * 陷阱往往不在第一步：铁滑车、敢死炮送的子**该吃**，真正的坑在吃完以后——
 * 他出车来捉，你不管它、或者舍不得还、或者贪心再吃一个，才上当。
 * 这种用 trapAfter 标出陷阱在破解的第几手之后；不在主线上的其它常见错着写在 wrong 里。
 *
 * **每一条都是引擎说了算，不是凭记忆写的。** 用户原话："算法的思考深度是有问题的"——
 * tools/check-tricks.ts 每个局面深算 10 秒（约 18 层）逐条复核：着法走得通、邪门着本身亏多少、
 * 破解是不是（接近）最好、上当亏多少、其它错着亏多少；复核不过的不许进库。
 * 找坑用的是 tools/trap-hunt.ts：被骗一方的每一步，浅算（几层）看着好、深算却亏一个半兵以上的，就是坑。
 * 下面 verified / wrong.loss 里的数就是深算复核出来的（车≈1000，破解方视角）。
 */
