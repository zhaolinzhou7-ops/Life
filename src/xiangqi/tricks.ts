/** 一串着法从开局走下去，走不通返回 null */
export function walkMoves(texts: string[]): { board: Board; color: Color; moves: Move[] } | null {
  let b = initialBoard();
  let c: Color = 'r';
  const moves: Move[] = [];
  for (const t of texts) {
    const m = textToMove(b, c, t, legalMoves(b, c));
    if (!m) return null;
    moves.push(m);
    b = applyMove(b, m);
    c = c === 'r' ? 'b' : 'r';
  }
  return { board: b, color: c, moves };
}

const same = (a: Move, b: Move) => a.fx === b.fx && a.fy === b.fy && a.tx === b.tx && a.ty === b.ty;

/** 邪门着走完之后的局面 → 是哪一条（认局面不认着法顺序，换个次序走到同一个局面也认得出） */
let byPos: Map<string, TrickOpening> | null = null;

function index(): Map<string, TrickOpening> {
  if (byPos) return byPos;
  const map = new Map<string, TrickOpening>();
  for (const t of TRICKS) {
    const w = walkMoves([...t.pre, t.trick.t]);
    if (w) map.set(toFen(w.board, w.color), t);
  }
  byPos = map;
  return map;
}

/** 这个局面是不是某个邪门着刚走完（轮到破解方） */
export function trickAt(board: Board, toMove: Color): TrickOpening | null {
  return index().get(toFen(board, toMove)) ?? null;
}

/** 走到陷阱分岔处的着法：前缀 + 邪门着 + 破解的前 trapAfter 手 */
export function lineToTrap(t: TrickOpening): string[] {
  return [...t.pre, t.trick.t, ...t.refute.slice(0, t.trapAfter ?? 0).map((s) => s.t)];
}

let byStage: Map<string, TrickOpening> | null = null;

/**
 * 这个局面是不是某条套路的"第二关"：邪门着已经破了（子吃到手了），
 * 对方刚走完捉子的那一手，轮到你——舍不得还子、往回救，就在这一步上当。
 * 只有 trapAfter > 0 的套路才有第二关。
 */
export function trickStageAt(board: Board, toMove: Color): TrickOpening | null {
  if (!byStage) {
    const map = new Map<string, TrickOpening>();
    for (const t of TRICKS) {
      if (!t.trapAfter) continue;
      const w = walkMoves(lineToTrap(t));
      if (w) map.set(toFen(w.board, w.color), t);
    }
    byStage = map;
  }
  return byStage.get(toFen(board, toMove)) ?? null;
}

/**
 * 陪练"走邪门布局"时，对手这一步该走什么：
 * 对局从开局起的着法恰好是某一条套路（前缀 + 邪门着）的开头、而且轮到对手走，就按那一条走下一手。
 * 陷阱在后面的套路（敢死炮、铁滑车），你吃了子之后它还会按套路出车来捉，一直走到第二关。
 * 有好几条都对得上时随机挑一条，但一旦挑定就一直走这一条（prefer）。
 * 对不上任何一条返回 null，对手照常走。
 */
export function trickMoveFor(moves: Move[], ai: Color, prefer?: string, rand = Math.random): { move: Move; trick: TrickOpening } | null {
  const fits: { move: Move; trick: TrickOpening }[] = [];
  for (const t of TRICKS) {
    if (t.by !== ai) continue;
    // 谱上的两条路：你照破解走，它照破解谱里它那一方的着法接着走（敢死炮吃了炮它还会追着捉）；
    // 你走了上当那一手，它照上当谱把便宜拿走。你走出谱外，它就照常下。
    for (const line of [lineToTrap(t), [...t.pre, t.trick.t, ...t.refute.map((x) => x.t)], [...lineToTrap(t), ...t.trap.map((x) => x.t)]]) {
      if (moves.length >= line.length) continue;
      const w = walkMoves(line.slice(0, moves.length + 1));
      if (!w) continue;
      if (!moves.every((m, i) => same(m, w.moves[i]))) continue;
      if (w.color === ai) continue;
      const mv = w.moves[moves.length];
      if (!fits.some((f) => f.trick === t && same(f.move, mv))) fits.push({ move: mv, trick: t });
    }
  }
  if (!fits.length) return null;
  return fits.find((f) => f.trick.id === prefer) ?? fits[Math.floor(rand() * fits.length)];
}


/** 上当那条线，从开局起的全部着法 */
export function trapFull(t: TrickOpening): string[] {
  return [...lineToTrap(t), ...trapLine(t).map((s) => s.t)];
}

/** 破解那条线，从开局起的全部着法 */
export function refuteFull(t: TrickOpening): string[] {
  return [...t.pre, t.trick.t, ...refuteLine(t).map((s) => s.t)];
}

function materialOf(b: Board, c: Color): number {
  let s = 0;
  for (const row of b) for (const p of row) if (p && p.t !== 'K') s += (p.c === c ? 1 : -1) * PIECE_VALUE[p.t];
  return s;
}

/**
 * 账本：沿着一条线，每走一手之后设套方的子力差和引擎局面分（都是设套方视角，车≈1000）。
 * "宁失一子，不失一先"就看这两条线之间差多少：子力少了、分没掉，差出来的就是先手的价钱。
 */
export function ledger(t: TrickOpening, which: 'trap' | 'refute'): { material: number[]; score: number[] } {
  const d = DEEP[t.id];
  const ev = (which === 'trap' ? d?.evTrap : d?.evRefute) ?? [];
  const w = walkMoves(which === 'trap' ? trapFull(t) : refuteFull(t));
  if (!w || !ev.length) return { material: [], score: [] };
  const sgn = t.by === 'r' ? 1 : -1;
  const material: number[] = [];
  let b = initialBoard();
  for (const m of w.moves.slice(0, ev.length)) {
    b = applyMove(b, m);
    material.push(materialOf(b, t.by));
  }
  return { material, score: ev.slice(0, material.length).map((v) => sgn * v) };
}

/**
 * 弃子的那一刻：你第一次把他送的东西吃到手的那一手之后。
 * 先在上当那条线上找；上当那条线是"不吃"（比如敢死炮不吃就被他先吃），就到破解那条线上找。
 * 只看邪门着之后八手以内——再往后是中局的子力交换，和弃子没关系了。
 * 返回哪条线、第几手（从 0 起）、子力差、局面分（设套方视角）；他一个子没少（比如空头炮那种），返回 null。
 */
export function sacrificeAt(t: TrickOpening): { line: 'trap' | 'refute'; ply: number; material: number; score: number } | null {
  const from = t.pre.length;
  for (const line of ['trap', 'refute'] as const) {
    const L = ledger(t, line);
    // 邪门着之前他已经少了的（双铁滑车第一匹马在铺垫里就送了）不算这一次
    const base = from ? Math.min(0, L.material[from - 1] ?? 0) : 0;
    // 你第一次把他送的东西吃到手：邪门着之后八手以内，他的子力比原来又少了一个兵以上
    for (let i = from; i < Math.min(L.material.length, from + 8); i++) {
      if (L.material[i] <= base - 90) return { line, ply: i, material: L.material[i], score: L.score[i] };
    }
  }
  return null;
}

/**
 * 坑：上当那条线上被骗一方走错的地方（深算比出来的，差 1.2 个兵以上）。
 * 走到输定（一步亏十个兵以上）就不往后数了——那之后的"错着"只是输法不同，不是坑。
 */
export function pitfalls(t: TrickOpening): { ply: number; played: string; best: string; loss: number }[] {
  const miss = DEEP[t.id]?.miss ?? {};
  const line = trapFull(t);
  const all = Object.entries(miss)
    .map(([k, v]) => ({ ply: Number(k), played: line[Number(k)], best: v.best, loss: v.loss }))
    .filter((x) => x.played)
    .sort((a, b) => a.ply - b.ply);
  const end = all.findIndex((x) => x.loss >= 1000);
  return end < 0 ? all : all.slice(0, end + 1);
}
