export interface TrickStep {
  /** 中文记谱 */
  t: string;
  /** 这一手在干什么 */
  why: string;
  /** 同样正确的其它走法（练习时走这些也算对） */
  alts?: string[];
  /** 备选走法自己的一句话（不写就说"和正解一样破得了"）——正解的理由套不到备选上 */
  altWhy?: string;
}

export interface TrickOpening {
  id: string;
  name: string;
  /** 江湖上的别名 */
  alias?: string;
  /** 谁在走邪门棋 */
  by: Color;
  level: '入门' | '初级' | '中级';
  /** 套路：它在赌你什么 */
  lure: string;
  /**
   * 精髓：他弃了什么、换来什么——"宁失一子，不失一先"落到这一套上是怎么回事。
   * 用户原话："要以象棋棋王的水平去破解，把这几个布局的精髓给讲透。"
   */
  essence: string;
  /** 走到邪门着之前的着法（双方） */
  pre: string[];
  /** 前面每一手是什么意思（和 pre 一一对应）：套路的第一步往往就藏在这里 */
  preWhy: string[];
  /** 陷阱拆解：看起来像什么、他在等你走什么、上当后怎么兑现、怎么认出来、破了之后他怎么走 */
  anatomy: {
    /** 表面上：这一手看起来像什么，为什么会让人放松或者心动 */
    looks: string;
    /** 陷阱在哪：他真正在等你走哪一步 */
    bait: string;
    /** 上当之后：他怎么一步步把便宜拿走（具体着法） */
    punish: string;
    /** 怎么认出来：看到什么信号就该警觉 */
    spot: string;
    /** 破了之后：他一般接着怎么走，你怎么接 */
    after: string;
  };
  /** 邪门着 */
  trick: TrickStep;
  /** 破解：从破解方这一手起的一小段 */
  refute: TrickStep[];
  /** 上当：最常见的错误应法和它的后果 */
  trap: TrickStep[];
  /**
   * 陷阱在破解的第几手之后（默认 0：邪门着之后马上就是陷阱）。
   * 比如 4 表示先按 refute[0..3] 走，到 refute[4] 这一手才分岔：
   * 走 refute[4] 是破解，走 trap[0] 是上当。必须是偶数（轮到破解方）。
   */
  trapAfter?: number;
  /**
   * 其它常见的错着（不在上当主线上的）：在破解第 at 手的位置（先按 refute[0..at-1] 走）
   * 走 t，比 refute[at] 差 loss（深算复核）。at 必须是偶数（轮到破解方）。
   */
  wrong?: { at: number; t: string; why: string; loss: number }[];
  /** 破解的道理——要记住的是这一句 */
  principle: string;
  /** 引擎复核过的数（破解方视角，车≈1000） */
  verified: {
    /** 邪门着本身比最好的走法亏多少（走邪门棋的一方） */
    trickLoss: number;
    /** 按破解走之后，破解方的分 */
    refuteScore: number;
    /** 上当那一手比破解差多少（有 trapAfter 的，在分岔那一步比） */
    trapLoss: number;
  };
}

