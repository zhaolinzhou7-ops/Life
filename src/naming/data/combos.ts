function parse(raw: string): string[] {
  return raw.split(/\s+/).map((s) => s.trim()).filter((s) => s.length === 2);
}

export interface ComboEntry {
  given: string;
  /** -1 偏女 / 0 中性 / 1 偏男。只是生成时的初筛，最终以用字的性别倾向为准 */
  lean: -1 | 0 | 1;
}

const seen = new Set<string>();
const out: ComboEntry[] = [];
for (const [raw, lean] of [
  [NEUTRAL, 0],
  [BOYISH, 1],
  [GIRLISH, -1],
] as [string, -1 | 0 | 1][]) {
  for (const g of parse(raw)) {
    if (seen.has(g)) continue;
    seen.add(g);
    out.push({ given: g, lean });
  }
}

export const COMBOS: ComboEntry[] = out;

/**
 * 从搭配库里反推出来的位置偏好。
 *
 * 有些字天生站在前面（碧云、翠竹、咏月里的碧/翠/咏），有些字天生站在后面
 * （佳木、秋白里的木/白）。把它们放反了就会得到「文碧」「木佳」这种半成品。
 *
 * 这个规律与其手写一份规则，不如直接从已经筛过的搭配里统计出来——数据长什么
 * 样，规则就是什么样，以后往搭配库里加词，规则自动跟着更新。
 *
 * 用在两个地方：辈分字/指定用字把一个位置占死之后，另一个位置该挑什么字；
 * 以及自由组合兜底时的最后一道关。
 */
export const HEAD_CHARS = new Set<string>();
export const TAIL_CHARS = new Set<string>();
/** 一个字在搭配库里出现过几次，用作「它到底像不像个名字用字」的粗略指标 */
export const COMBO_CHAR_COUNT = new Map<string, number>();

for (const c of out) {
  HEAD_CHARS.add(c.given[0]);
  TAIL_CHARS.add(c.given[1]);
  for (const ch of c.given) COMBO_CHAR_COUNT.set(ch, (COMBO_CHAR_COUNT.get(ch) ?? 0) + 1);
}
