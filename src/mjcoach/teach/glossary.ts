/** 按分组取术语 */
export function termsByGroup(): { group: Term['group']; terms: Term[] }[] {
  const groups: Term['group'][] = ['基本', '牌效率', '四川规则', '防守', '番型'];
  return groups.map((g) => ({ group: g, terms: TERMS.filter((t) => t.group === g) }));
}

/** 在一段文案里找出现过的术语（给「这些词是什么意思」用） */
export function termsIn(text: string): Term[] {
  const out: Term[] = [];
  for (const t of TERMS) {
    const keys = [t.name, ...(t.alias ?? [])];
    if (keys.some((k) => text.includes(k))) out.push(t);
  }
  return out;
}

export function findTerm(word: string): Term | undefined {
  return TERMS.find((t) => t.name === word || t.alias?.includes(word));
}
